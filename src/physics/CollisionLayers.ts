/**
 * Matter.js collision category & mask constants for multi-layer bridges/viaducts.
 *
 * Layer 0 = ground level; Layer 1 = elevated viaduct deck.
 * Ramp side walls (RAMP_WALL) block both layers (solid embankment).
 * Bridge guardrails (BRIDGE_RAIL) block ONLY Layer 1 so ground traffic passes
 * freely underneath the elevated span without colliding with overhead rails.
 */
export const COLLISION_CAT = {
  GROUND_OBS: 0x0001,
  TRUCK_L0: 0x0002,
  TRAILER_L0: 0x0004,
  BLOCKER_L0: 0x0008,
  RAMP_WALL: 0x0010,
  FRONT_L0: 0x0020,
  BRIDGE_RAIL: 0x0040,
  TRUCK_L1: 0x0100,
  TRAILER_L1: 0x0200,
  BLOCKER_L1: 0x0400,
  FRONT_L1: 0x0800,
} as const;

export const COLLISION_MASK = {
  GROUND_OBS: COLLISION_CAT.TRUCK_L0 | COLLISION_CAT.TRAILER_L0,
  RAMP_WALL: 0xffff,
  BRIDGE_RAIL: COLLISION_CAT.TRUCK_L1 | COLLISION_CAT.TRAILER_L1,

  TRUCK_L0: COLLISION_CAT.GROUND_OBS | COLLISION_CAT.RAMP_WALL | COLLISION_CAT.BLOCKER_L0,
  TRUCK_L1: COLLISION_CAT.BRIDGE_RAIL | COLLISION_CAT.RAMP_WALL | COLLISION_CAT.BLOCKER_L1,
  FRONT_L0: COLLISION_CAT.TRAILER_L0,
  FRONT_L1: COLLISION_CAT.TRAILER_L1,

  TRAILER_COUPLED_L0: COLLISION_CAT.GROUND_OBS | COLLISION_CAT.RAMP_WALL | COLLISION_CAT.TRAILER_L0,
  TRAILER_COUPLED_L1: COLLISION_CAT.BRIDGE_RAIL | COLLISION_CAT.RAMP_WALL | COLLISION_CAT.TRAILER_L1,

  TRAILER_PARKED_L0: COLLISION_CAT.GROUND_OBS | COLLISION_CAT.RAMP_WALL | COLLISION_CAT.FRONT_L0,
  TRAILER_PARKED_L1: COLLISION_CAT.BRIDGE_RAIL | COLLISION_CAT.RAMP_WALL | COLLISION_CAT.FRONT_L1,

  BLOCKER_L0: COLLISION_CAT.TRUCK_L0 | COLLISION_CAT.TRAILER_L0,
  BLOCKER_L1: COLLISION_CAT.TRUCK_L1 | COLLISION_CAT.TRAILER_L1,
} as const;
